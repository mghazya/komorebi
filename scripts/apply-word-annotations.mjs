function main() {
  console.log(`Verifying and applying words for all ${Object.keys(ALL_WORDS_BY_ID).length} questions/follow-ups...`);
  for (let i = 1; i <= 7; i++) {
    const packFile = path.join(ROOT, 'data', `context-pack-${i}.json`);
    const pack = JSON.parse(fs.readFileSync(packFile, 'utf8'));

    for (const pat of pack.patterns) {
      for (const q of pat.questions) {
        if (!ALL_WORDS_BY_ID[q.id]) {
          throw new Error(`Missing word annotations for primary question: ${q.id}`);
        }
        q.words = ALL_WORDS_BY_ID[q.id];

        const fu = q.followUp;
        if (!ALL_WORDS_BY_ID[fu.id]) {
          throw new Error(`Missing word annotations for follow-up question: ${fu.id}`);
        }
        fu.words = ALL_WORDS_BY_ID[fu.id];
      }
    }

    // Validate the pack structure and word reconstructions
    validateContextPack(pack);
    fs.writeFileSync(packFile, JSON.stringify(pack, null, 2) + '\n', 'utf8');
    console.log(`Pack ${i} validated and updated with tap-to-read word help.`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
